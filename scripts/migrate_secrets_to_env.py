#!/usr/bin/env python3
"""
Migrate secrets from SQLite (global_credentials) to a local .env file without printing any secret values.
- Backs up configurations/config.db to configurations/config.db.bak-<timestamp>
- Backs up existing .env to .env.bak-<timestamp> (if present)
- Writes the following env vars (when available):
    LEGAL_EAGLE_OPENAI_API_KEY         (not stored in DB; left blank unless already in environment)
    LEGAL_EAGLE_TWITTER_BEARER_TOKEN   ← global_credentials.twitter_bearer_token
    LEGAL_EAGLE_GMAIL_EMAIL_SENDER     ← global_credentials.global_sender_email or smtp_username
    LEGAL_EAGLE_GMAIL_APP_PASSWORD     ← global_credentials.smtp_password
    LEGAL_EAGLE_ADMIN_SECRET           ← default 'local-only-admin' (non-sensitive)
Optional Gmail OAuth fields are not stored in DB and will be left blank.

This script does NOT print secret values to stdout.
"""

import os
import sys
import shutil
from datetime import datetime

# Ensure project root on sys.path so we can import configurations.db
BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

from configurations.db import get_connection, create_schema_if_needed, get_global_credentials  # type: ignore


def timestamp() -> str:
    return datetime.utcnow().strftime("%Y%m%d-%H%M%S")


def backup_file(src_path: str, dst_prefix: str) -> str:
    """
    Backup a file if it exists. Returns backup path or '' if src missing.
    """
    if not os.path.exists(src_path):
        return ""
    bak_path = f"{dst_prefix}.{timestamp()}"
    shutil.copy2(src_path, bak_path)
    return bak_path


def fetch_db_creds() -> dict:
    """
    Fetch the singleton global_credentials (id=1) from SQLite.
    Returns {} if none.
    """
    conn = get_connection()
    create_schema_if_needed(conn)
    row = get_global_credentials(conn) or {}
    conn.close()
    return row


def compose_env_values(db_row: dict) -> dict:
    """
    Compose environment variables from DB row.
    Avoid printing secrets; return dict of values (may contain None).
    """
    # DB columns available (per configurations/db.py):
    # twitter_api_key, twitter_api_secret, twitter_bearer_token,
    # smtp_host, smtp_port, smtp_username, smtp_password, smtp_use_tls, global_sender_email
    twitter_bearer = db_row.get("twitter_bearer_token")
    smtp_username = db_row.get("smtp_username")
    smtp_password = db_row.get("smtp_password")
    sender_email = db_row.get("global_sender_email") or smtp_username

    # OPENAI key is NOT in DB schema; try existing environment, else leave blank
    openai_key = os.environ.get("LEGAL_EAGLE_OPENAI_API_KEY")

    values = {
        "LEGAL_EAGLE_OPENAI_API_KEY": openai_key or "",
        "LEGAL_EAGLE_TWITTER_BEARER_TOKEN": twitter_bearer or "",
        "LEGAL_EAGLE_GMAIL_EMAIL_SENDER": sender_email or "",
        "LEGAL_EAGLE_GMAIL_APP_PASSWORD": smtp_password or "",
        # Non-sensitive default for admin secret
        "LEGAL_EAGLE_ADMIN_SECRET": os.environ.get("LEGAL_EAGLE_ADMIN_SECRET", "local-only-admin"),
        # Optional Gmail OAuth (not available in DB)
        "LEGAL_EAGLE_GMAIL_CLIENT_ID": "",
        "LEGAL_EAGLE_GMAIL_CLIENT_SECRET": "",
        "LEGAL_EAGLE_GMAIL_REFRESH_TOKEN": "",
        "LEGAL_EAGLE_GMAIL_SCOPE": "https://mail.google.com/ https://www.googleapis.com/auth/gmail.send",
        "LEGAL_EAGLE_GMAIL_TOKEN_URI": "https://oauth2.googleapis.com/token",
    }
    return values


def write_env_file(env_values: dict, env_path: str = ".env") -> str:
    """
    Write .env file with provided values. Backup existing .env first if present.
    Returns path written.
    """
    # Backup existing .env if present
    bak_env = ""
    if os.path.exists(env_path):
        bak_env = backup_file(env_path, f"{env_path}.bak")

    lines = [
        "# Generated by migrate_secrets_to_env.py - DO NOT COMMIT THIS FILE",
        "# Fill or adjust values as needed. Secrets intentionally not printed to console.",
        "",
    ]
    for k, v in env_values.items():
        # Write as key=value; do not add quotes to keep dotenv simple
        lines.append(f"{k}={v}")

    with open(env_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    return bak_env or ""


def main() -> None:
    # Backup DB if present
    db_path = os.path.join(BASE_DIR, "configurations", "config.db")
    db_bak = backup_file(db_path, os.path.join(BASE_DIR, "configurations", "config.db.bak"))

    # Fetch DB row
    db_row = fetch_db_creds()

    # Compose env values
    env_values = compose_env_values(db_row)

    # Write .env
    env_bak = write_env_file(env_values, env_path=os.path.join(BASE_DIR, ".env"))

    # Print summary (no secrets)
    filled = {k: bool(v) for k, v in env_values.items()}
    print("✅ .env written at project root.")
    if db_bak:
        print(f"🗄️ DB backup: {db_bak}")
    if env_bak:
        print(f"🗄️ Previous .env backup: {env_bak}")
    # Summarize presence without revealing values
    print("Presence (True means set/non-empty):")
    for k in ["LEGAL_EAGLE_OPENAI_API_KEY", "LEGAL_EAGLE_TWITTER_BEARER_TOKEN", "LEGAL_EAGLE_GMAIL_EMAIL_SENDER", "LEGAL_EAGLE_GMAIL_APP_PASSWORD"]:
        print(f"  - {k}: {filled.get(k)}")
    print("Note: OPENAI key is not stored in DB; set it manually if False.")

if __name__ == "__main__":
    main()
